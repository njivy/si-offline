import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fixtures = path.join(root, 'public', 'fixtures');
const outZip = path.join(fixtures, 'job-minimal.zip');
const outSrcZip = path.join(root, 'src', 'fixtures', 'job-minimal.zip');
const outSrcJs = path.join(root, 'src', 'fixtures', 'job-minimal.js');

const secFiles = readdirSync(fixtures).filter((f) => f.endsWith('.sec')).sort();
if (secFiles.length < 1) {
  console.error('No .sec files in public/fixtures');
  process.exit(1);
}

const py = `
import json, zipfile, base64, pathlib
fixtures = ${JSON.stringify(fixtures)}
out = ${JSON.stringify(outZip)}
js_path = ${JSON.stringify(outSrcJs)}
files = ${JSON.stringify(secFiles)}
manifest = {
  "format": "si-offline-job",
  "formatVersion": 1,
  "exportedAt": "2026-09-22T20:00:00.000Z",
  "job": {
    "name": "FIXTURE",
    "title": "Offline SI fixture Job",
    "contract": "",
    "location": "",
    "leadSpecifier": ""
  },
  "marking": None,
}
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    z.writestr("si-offline-job.json", json.dumps(manifest, indent=2))
    for name in files:
        z.write(str(pathlib.Path(fixtures) / name), name)
raw = pathlib.Path(out).read_bytes()
b64 = base64.b64encode(raw).decode("ascii")
pathlib.Path(js_path).parent.mkdir(parents=True, exist_ok=True)
pathlib.Path(js_path).write_text(
    "/** Auto-generated by scripts/build-fixture-job.mjs — do not edit. */\\n"
    f"export default 'data:application/zip;base64,{b64}';\\n"
)
print("wrote", out)
print("wrote", js_path)
`;

const r = spawnSync('python3', ['-c', py], { encoding: 'utf8' });
if (r.status !== 0) {
  console.error(r.stderr || r.stdout);
  process.exit(r.status || 1);
}
console.log(r.stdout.trim());
mkdirSync(path.dirname(outSrcZip), { recursive: true });
copyFileSync(outZip, outSrcZip);
console.log('copied', outSrcZip);
